import re
import logging
from subprocess import run
from DatabaseEditor.DatabaseEditor import DatabaseEditor


class DataCleaner:
    def __init__(self, site_name: str, site_id: int, database:str = "migration.db", u:str = "infodba", p:str = "infodba", g:str = "dba"):
        self.siteName = site_name
        self.siteID = site_id
        self.u = u
        self.p = p
        self.g = g
        self.db = DatabaseEditor(database)



    def writeInputFile(self, file:str, item_list: list[str]) -> None:
        """
        Writes comma separed list of item ids
        Args:
            file: path of filename
            item_list: list of item IDs"""
        
        with open(file, "w") as file:
            file.write(",".join(item_list))

        return

    def item_report(self, input_file: str, output_file: str) -> int:
        """
        Provided an input file comma separated with item ids
        Args:
            input_file: path of comma separated IDs filename
            output_file: output file

        Returns:
            int: result code of item_report utility

        """
        logging.info(f"Running item_report with {input_file} outputing to {output_file}")
        command = f"cmd.exe /c item_report -u={self.u} -p={self.p} -g={self.g} -f=report -itemidsfile={input_file} -outfile={output_file}"
        process = run(command.split(" "), capture_output=True, shell=True)

        if process.returncode == 0:
            logging.info("Successfully ran item_report")
        else:
            logging.error("Failed to run item_report utility")

        return process.returncode


    def parseReportFile(self, file: str) -> list[str]:
        """
        Parses result from item_report to find items that are not part of the home site
        Args:
            file: path of report file generated by item_report
        Returns:
            list: list of puid to correct ID
        """

        pattern = re.compile(r"(?P<UID>[^\|]*)\|([^\|]*)\|(?P<name>[^\|]*)\|(?P<item_id>[^\|]*)\|(?P<type>[^\|]*)\|(?P<owning_site>[^\|]*)\|(.*)")
        puidList = []
        with open(file, "r") as file:
            next(file)
            for line in file:
                if match := pattern.match(line):
                    gd = match.groupdict()
                    if gd["owning_site"] != self.siteName:
                        logging.info(f"INCONSISTENCY FOUND:\n\tObject of type: {gd["type"]}\n\tObject Name: {gd["name"]}\n\tUnder Item: {gd["item_id"]}\n\tOwned By: {gd["owning_site"]}")
                        puidList.append(gd["UID"])
                else:
                    logging.warning("Line didn't fit pattern")

        return puidList


    def writeFlipFile(self, file: str, puids: list[str]) -> None:
        """
        Writes file with list of puids to flip ownership
        Args:
            file: file path to write
            puids: list of puids """

        with open(file, "w") as file:
            file.write("\n".join(puids))


    def flipOwnership(self, file) -> int:
        """
        Provided an input file with each line as puids
        Args:
            file: file path conatining line separated puids to change ownership

        Returns:
            int: result code of item_report utility
        """
        logging.info(f"Running tcxml_ownership_recovery with {file} outputing")
        command = f"cmd.exe /c tcxml_ownership_recovery -u={self.u} -p={self.p} -g={self.g} -action=flip -inputuidfile={file} -targetsite={self.siteID}"
        process = run(command.split(" "), capture_output=True, shell=True)

        if process.returncode == 0:
            logging.info("Successfully ran tcxml_ownership_recovery")
        else:
            logging.error("Failed to run tcxml_ownership_recovery utility")

        return process.returncode


